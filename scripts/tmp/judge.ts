const v = await judgeAndImprove({
  employeeId: "sonny",
  request: "اكتب منشور إنستقرام عن عرض عطر عود فاخر بخصم محدود، بنبرة واثقة ودعوة عمل واحدة.",
  output: weak,
  criteria: ["دعوة عمل واحدة فقط", "بلا مبالغة أو وعود مطلقة", "يذكر المنتج والخصم بوضوح"],
  bannedWords: ["الأفضل في العالم", "مجاناً 100%"],
});
console.log("score", v.score, "revised", v.revised);
console.log("issues", v.issues);
console.log("---\n" + v.output);
process.exit(0);
